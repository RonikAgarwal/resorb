// ─── HELPER FUNCTIONS ─────────────────────────────────────────────────────────

export function getAllProducts() {
  return products;
}

export function getProductById(id) {
  return products.find((p) => p.id === id) || null;
}

export function getProductsByCategory(categorySlug) {
  return products.filter((p) => p.category === categorySlug);
}

export function getPopularProducts() {
  return products.filter((p) => p.popular);
}

function normalizeSearchValue(value) {
  return (value || "").toLowerCase().replace(/[^a-z0-9]+/g, "");
}

export function searchProducts(query = "", options = {}) {
  const q = query.toLowerCase().trim();
  const category = options.category?.toLowerCase().trim();
  const brand = options.brand?.toLowerCase().trim();
  const hasQuery = q.length >= 2;

  if (!hasQuery && !category && !brand) return [];

  return products.filter((p) => {
    if (category && p.category !== category) return false;
    if (
      brand &&
      p.brand !== brand &&
      !p.compatibleBrands.some((b) => normalizeSearchValue(b) === normalizeSearchValue(brand))
    ) {
      return false;
    }

    if (!hasQuery) return true;

    return (
      p.name.toLowerCase().includes(q) ||
      p.title.toLowerCase().includes(q) ||
      p.sku.toLowerCase().includes(q) ||
      (p.brand || "").toLowerCase().includes(q) ||
      p.description.toLowerCase().includes(q) ||
      p.compatibleBrands.some((b) => b.toLowerCase().includes(q)) ||
      p.compatibleModels.some((m) => m.toLowerCase().includes(q)) ||
      p.tags.some((t) => t.toLowerCase().includes(q)) ||
      p.category.replace(/-/g, " ").includes(q)
    );
  });
}

export function getRelatedProducts(product, limit = 4) {
  return products
    .filter((p) => p.category === product.category && p.id !== product.id)
    .slice(0, limit);
}
